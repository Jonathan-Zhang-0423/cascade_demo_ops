func boundedHoldMS(holdMS int, durationMS int) int {
	if holdMS > 0 {
		if holdMS > 10000 {
			return 10000
		}
		return holdMS
	}
	if durationMS <= 0 {
		return 0
	}
	if durationMS > 10000 {
		return 10000
	}
	return durationMS
}

func preActionPauseMS(actionType model.GraphActionType, durationMS int) int {
	if durationMS < 10000 {
		return 0
	}
	switch actionType {
	case model.GraphActionClick, model.GraphActionFill, model.GraphActionSelect, model.GraphActionUpload, model.GraphActionPress, model.GraphActionGesture:
		return 1200
	case model.GraphActionInspect, model.GraphActionWait:
		return 0
	default:
		return 800
	}
}

func jsString(value string) string {
	return strconv.Quote(value)
}

func jsBool(value bool) string {
	if value {
		return "true"
	}
	return "false"
}

func jsJSON(value any) string {
	data, err := json.Marshal(value)
	if err != nil {
		return "null"
	}
	return string(data)
}

func jsIdentifier(value string) string {
	value = strings.TrimSpace(value)
	if value == "" {
		return "value"
	}
	var builder strings.Builder
	for i, r := range value {
		allowed := (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '_'
		if i > 0 {
			allowed = allowed || (r >= '0' && r <= '9')
		}
		if allowed {
			builder.WriteRune(r)
		} else {
			builder.WriteByte('_')
		}
	}
	out := strings.Trim(builder.String(), "_")
	if out == "" {
		return "value"
	}
	return out
}

func looksSensitiveLiteral(value string) bool {
	lower := strings.ToLower(value)
	for _, token := range []string{"password", "passwd", "secret", "api_key", "apikey", "private key", "bearer ", "sk-"} {
		if strings.Contains(lower, token) {
			return true
		}
	}
	return strings.Contains(value, "BEGIN PRIVATE KEY")
}


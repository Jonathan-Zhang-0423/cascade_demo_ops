func writeStepAssertions(builder *strings.Builder, step model.ScriptStep, actionType model.GraphActionType, selector string, targetURL string, timeoutMS int) {
	if actionType == model.GraphActionInspect || actionType == model.GraphActionWait {
		builder.WriteString("  await ctx.log.info(\"observation step validation is non-blocking\", { nodeId: " + jsString(step.NodeID) + " });\n")
		return
	}
	if scriptStepIsRuntimeAdaptive(step) {
		builder.WriteString("  await ctx.log.info(\"runtime adaptive step validation is diagnostic-only\", { nodeId: " + jsString(step.NodeID) + " });\n")
		return
	}
	expected := firstNonEmpty(step.ExpectedOutcome, step.Narrative.Caption, step.Narrative.Voiceover)
	if expected != "" {
		if selector == "" || selectorUsableForBlockingAssertion(selector) {
			builder.WriteString("  await ctx.assert.step(" + jsString(step.NodeID) + ", " + jsString(expected) + ", { selector: " + jsString(selector) + ", url: " + jsString(targetURL) + ", timeout: " + fmt.Sprint(timeoutMS) + " });\n")
		} else {
			builder.WriteString("  await ctx.log.info(\"skip blocking assert.step for low-quality selector\", { nodeId: " + jsString(step.NodeID) + ", selector: " + jsString(selector) + " });\n")
		}
	}
	for _, validation := range step.Validations {
		if !validation.Required || validation.Severity != "blocking" {
			continue
		}
		validationSelector := firstNonEmpty(validation.Target.Selector, selector)
		if validationSelector != "" && !selectorUsableForBlockingAssertion(validationSelector) {
			builder.WriteString("  await ctx.log.info(\"skip blocking validation for low-quality selector\", { nodeId: " + jsString(step.NodeID) + ", validationId: " + jsString(validation.ID) + ", selector: " + jsString(validationSelector) + " });\n")
			continue
		}
		validationExpected := fmt.Sprint(validation.Expected)
		if validation.Assertion != "" {
			validationExpected = validation.Assertion
		}
		if validationSelector != "" && validationExpected != "" && validationExpected != "<nil>" {
			builder.WriteString("  await ctx.assert.text(" + jsString(validationSelector) + ", " + jsString(validationExpected) + ", { nodeId: " + jsString(step.NodeID) + ", validationId: " + jsString(validation.ID) + ", timeout: " + fmt.Sprint(timeoutMS) + " });\n")
		} else if validationSelector != "" {
			builder.WriteString("  await ctx.assert.visible(" + jsString(validationSelector) + ", { nodeId: " + jsString(step.NodeID) + ", validationId: " + jsString(validation.ID) + ", timeout: " + fmt.Sprint(timeoutMS) + " });\n")
		}
		if validation.Target.URL != "" {
			builder.WriteString("  await ctx.assert.url(" + jsString(validation.Target.URL) + ", { nodeId: " + jsString(step.NodeID) + ", validationId: " + jsString(validation.ID) + ", timeout: " + fmt.Sprint(timeoutMS) + " });\n")
		}
	}
}

func scriptStepIsRuntimeAdaptive(step model.ScriptStep) bool {
	if strings.Contains(strings.ToLower(strings.Join(stepNodeValidationKinds(step.Validations), " ")), "runtime_adaptive") {
		return true
	}
	for _, candidate := range step.Action.Target.SelectorAlternatives {
		if strings.Contains(strings.ToLower(candidate.Source), "runtime_adaptive") {
			return true
		}
	}
	for _, candidate := range step.PageTarget.SelectorAlternatives {
		if strings.Contains(strings.ToLower(candidate.Source), "runtime_adaptive") {
			return true
		}
	}
	return false
}

func stepNodeValidationKinds(validations []model.ValidationSpec) []string {
	kinds := make([]string, 0, len(validations))
	for _, validation := range validations {
		kinds = append(kinds, validation.Kind)
	}
	return kinds
}

func scriptInputExpression(step model.ScriptStep) (string, error) {
	if step.Action.SecretRef != "" {
		return "await ctx.secrets.get(" + jsString(step.Action.SecretRef) + ")", nil
	}
	if step.Action.InputRef != "" {
		return "await ctx.secrets.getInput(" + jsString(step.Action.InputRef) + ")", nil
	}
	if looksSensitiveLiteral(step.Action.Value) {
		return "", fmt.Errorf("step %s contains sensitive inline value; use secret_ref or input_ref", step.NodeID)
	}
	return jsString(step.Action.Value), nil
}

